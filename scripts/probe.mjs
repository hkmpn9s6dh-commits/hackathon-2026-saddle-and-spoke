import { chromium } from "playwright-core";
const exe = process.env.CHROME_PATH ?? `${process.env.USERPROFILE}/AppData/Local/Google/Chrome/Application/chrome.exe`;
const browser = await chromium.launch({ executablePath: exe, headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on("pageerror", (e) => console.log("PAGEERROR", String(e)));
page.on("console", (m) => { if (m.type() === "error") console.log("CONSOLE", m.text()); });
await page.goto("http://127.0.0.1:5173/", { waitUntil: "networkidle" });
await page.waitForFunction(() => window.__saddle?.ready === true, { timeout: 15000 });
const tools = await page.evaluate(() => [...window.__saddle.network.agents.entries()].map(([k, v]) => [k, v.tools.map(t => `${t.kind}:${t.name}`)]));
console.log("tools", JSON.stringify(tools));
await page.fill("#input", "Third gear jumps when I push hard uphill.");
await page.click("#send");
await page.waitForTimeout(900);
console.log("modal class:", await page.evaluate(() => document.querySelector("#modal")?.className));
console.log("modal title:", await page.evaluate(() => document.querySelector("#modal-title")?.textContent));
console.log("modal body html:", (await page.evaluate(() => document.querySelector("#modal-body")?.innerHTML ?? "")).slice(0, 300));
console.log("lastRun:", JSON.stringify(await page.evaluate(() => window.__saddle.lastRun)));
console.log("trace tail:", await page.evaluate(() => window.__saddle.trace.history().slice(-6).map(e => e.kind + " " + e.message)));
await browser.close();
